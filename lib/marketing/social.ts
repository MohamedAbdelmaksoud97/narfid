export function postsFor(platform: PlatformId) {
  return socialPosts.filter((post) => post.platform === platform);
}
export function postFilename(post: SocialPost) {
  return `${post.id}-${post.theme}.png`;
}
export function postAsset(post: SocialPost, preview = false) {
  return `/api/board/marketing/assets/${post.platform}/${post.id}-${post.theme}${preview ? ".preview.webp" : ".png"}`;
}
export function suggestedWeek(post: SocialPost) {
  const index = Number(post.id);
  return index <= 10
    ? index <= 3
      ? 1
      : index <= 6
        ? 2
        : index <= 8
          ? 3
          : 4
    : 5 + Math.floor((index - 11) / 3);
}
export function trackedDestination(post: SocialPost) {
  return `${post.destination}?utm_source=${post.platform}&utm_medium=organic_social&utm_campaign=nerved_launch&utm_content=${post.platform}_${post.id}`;
}

