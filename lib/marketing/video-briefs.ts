export function findVideo(id: string) {
  return videoBriefs.find((video) => video.id === id);
}
// Rotate pillars without making a commitment to dates or a publication cadence.
export const suggestedVideoOrder = (() => {
  const groups = ["operations", "product", "decisions", "brand"].map((pillar) =>
    videoBriefs.filter((video) => video.pillar === pillar),
  );
  const order: string[] = [];
  while (groups.some((group) => group.length))
    for (const group of groups) {
      const next = group.shift();
      if (next) order.push(next.id);
    }
  return order;
})();
