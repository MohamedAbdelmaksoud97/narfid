export function createProductPosts(platform: SocialPlatform): SocialPost[] {
  const position = { snapchat: 0, instagram: 1, x: 2, facebook: 3 }[
    platform.id
  ];
  return topics.map((topic, index) => {
    const headline = topic.headlines[position];
    const caption =
      platform.id === "x"
        ? `${headline.replaceAll("\n", " ")} ${topic.subline} نرفد تربط ${topic.points.join("، ")}. احجز عرضًا يناسب مؤسستك. #نرفد`
        : platform.id === "snapchat"
          ? `${headline.replaceAll("\n", " ")}\n\n${topic.subline}\n${topic.explain}\n\n${topic.question}\nناقش احتياج مؤسستك مع نرفد، واحجز عرضًا توضيحيًا. #نرفد`
          : platform.id === "instagram"
            ? `${headline.replaceAll("\n", " ")}\n\n${topic.explain}\n\nفي المراجعة: ${topic.points.join("، ")}.\n\n${topic.question}\nاحفظ الفكرة لمراجعتها مع فريقك، واحجز عرضًا توضيحيًا لنرفد يناسب مؤسستك.\n#نرفد #إدارة_الأندية #المؤسسات_الرياضية`
            : `${headline.replaceAll("\n", " ")}\n\n${topic.scenario}\n\n${topic.explain}\n\n${topic.question}\nشارك السؤال مع مسؤول التشغيل، وناقش معنا كيف تبدو هذه الدورة في مؤسستك خلال عرض نرفد التوضيحي.\n#نرفد #إدارة_المؤسسات_الرياضية`;
    return {
      id: String(index + 11).padStart(2, "0"),
      platform: platform.id,
      theme: topic.theme,
      scene: topic.scene,
      screenshot: topic.screen,
      imageStyle: index % 3 === 0 ? "wide" : "focus",
      eyebrow: topic.eyebrow,
      headline,
      subline: topic.subline,
      points: topic.points,
      caption,
      alt: `${headline.replaceAll("\n", " ")} — ${topic.subline} ${topic.points.join("، ")}. لقطة فعلية من واجهة ${productScreens[topic.screen].label}، بهوية نرفد وبيانات عرض تجريبية؛ ليست بيانات عميل أو نتائج أداء.`,
      cta: index === 19 ? "اختر ما تريد مشاهدته" : "احجز عرضًا توضيحيًا",
      goal: index === 19 ? "طلب عرض" : index % 4 === 0 ? "تقييم" : "تعليم",
      audience:
        index >= 14 && index <= 17
          ? "مالك المؤسسة ومدير العمليات أو الفرع"
          : "مسؤول التشغيل والفريق المعني بدورة العمل",
      destination: topic.destination,
      layout: "product",
    };
  });
}
